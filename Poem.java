
public class Poem{
      
     private String name;
     private int numLines;
     
     
     public Poem(String name, int numLines){
     
      this.name = name;
      this.numLines = numLines;
     
     }
     
     public String getName(){
     
      return this.name;
     
     }
     
     public int getNumlines(){
     
      return this.numLines;

     
     }
    
}